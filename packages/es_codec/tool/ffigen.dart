import 'dart:io';

import 'package:ffigen/ffigen.dart';

/// Regenerate with: dart run tool/ffigen.dart (needs LLVM/libclang).
///
/// Writes the TurboJPEG v3 API bindings (libjpeg-turbo, ADR-002) for the native
/// asset built by hook/build.dart (lib/src/c_library.dart).
Future<void> main() async {
  final root = Platform.script.resolve('../');
  await _generate(
    root: root,
    header: 'third_party/libjpeg-turbo/src/turbojpeg.h',
    functions: {
      'tj3InitVersion', // tj3Init() is a macro over this
      'tj3Destroy',
      'tj3Set',
      'tj3Get',
      'tj3Compress8',
      'tj3Free',
      'tj3GetErrorStr',
      'tj3GetErrorCode',
    },
    enums: {'TJINIT', 'TJSAMP', 'TJPF', 'TJPARAM', 'TJERR'},
    macros: {'TURBOJPEG_VERSION_NUMBER'},
    out: 'turbojpeg',
    license: '''
// Bindings for libjpeg-turbo 3.2.1 turbojpeg.h:
// Copyright (C) 2009-2026 D. R. Commander. All Rights Reserved.
// Modified BSD licence, see third_party/libjpeg-turbo/LICENSE.md.
''',
  );
}

Future<void> _generate({
  required Uri root,
  required String header,
  required Set<String> functions,
  Set<String> enums = const {},
  Set<String> macros = const {},
  required String out,
  required String license,
}) {
  return FfiGenerator(
    input: Input(entryPoints: [root.resolve(header)]),
    visitors: [
      Visitor(
        func: (node) {
          if (!functions.contains(node.name)) return;
          node.isIncluded = true;
          node.isLeaf = true; // no callbacks into Dart; run on a worker isolate
          node.recordUse = true; // lets hook/link.dart tree-shake unused symbols
        },
        enumClass: (node) {
          if (enums.contains(node.name)) node.isIncluded = true;
        },
        macroConstant: (node) {
          if (macros.contains(node.name)) node.isIncluded = true;
        },
      ),
    ],
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/$out.g.dart')),
      style: const NativeExternalBindings(
        assetId: 'package:es_codec/es_codec_native',
      ),
      recordUseMapping: root.resolve('lib/src/$out.record_use_mapping.g.dart'),
      preamble: '''
// Copyright (c) 2026 ExactSize authors. All rights reserved.
$license// Generated by package:ffigen. Do not edit manually.
// To regenerate: dart run tool/ffigen.dart

// ignore_for_file: type=lint, unused_import, unused_element, experimental_member_use
''',
    ),
  ).generate();
}
