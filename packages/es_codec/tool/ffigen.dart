import 'dart:io';

import 'package:ffigen/ffigen.dart';

const _functions = {'es_probe_add', 'es_probe_unused'};

/// Regenerate with: dart run tool/ffigen.dart (needs LLVM/libclang).
Future<void> main() async {
  final root = Platform.script.resolve('../');
  await FfiGenerator(
    input: Input(entryPoints: [root.resolve('src/es_probe.h')]),
    visitors: [
      Visitor(
        func: (node) {
          if (!_functions.contains(node.name)) return;
          node.isIncluded = true;
          node.isLeaf = true; // short, no callbacks into Dart
          node.recordUse = true; // lets hook/link.dart tree-shake unused symbols
        },
      ),
    ],
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/es_probe.g.dart')),
      recordUseMapping: root.resolve(
        'lib/src/es_probe.record_use_mapping.g.dart',
      ),
      preamble: '''
// Copyright (c) 2026 ExactSize authors. All rights reserved.
// Generated by package:ffigen. Do not edit manually.
// To regenerate: dart run tool/ffigen.dart

// ignore_for_file: type=lint, unused_import, unused_element, experimental_member_use
''',
    ),
  ).generate();
}
